/**
 * Suggerisce un'icona basata sul nome della categoria
 */
export function suggestIcon(categoryName: string): string {
  const normalizedName = categoryName.toLowerCase().trim();

  // Cerca corrispondenza esatta
  if (ICON_SUGGESTIONS[normalizedName]) {
    return ICON_SUGGESTIONS[normalizedName];
  }

  // Cerca corrispondenza parziale
  for (const [keyword, icon] of Object.entries(ICON_SUGGESTIONS)) {
    if (normalizedName.includes(keyword) || keyword.includes(normalizedName)) {
      return icon;
    }
  }

  // Default fallback
  return '📦';
}

